function ownerId() {
  return cy
    .env<{ test_users: [Cypress.TestUser, Cypress.TestUser] }>(["test_users"])
    .then(({ test_users }) => {
      const owner = test_users[0];
      if (!owner) {
        throw new Error("test_users[0] is missing");
      }
      return owner.user_id;
    });
}

// Types Markdown into the reusable editor's visual (MDXEditor) contenteditable
// surface. The create and edit forms both mount the same editor, so the same
// helper serves both. The surface is identified by the stable adapter data-cy.
function typeInEditor(fieldCy: string, text: string) {
  cy.get(`[data-cy='${fieldCy}'] [data-cy='mdx-visual-editor']`, {
    timeout: 20000,
  }).should("exist");
  cy.get(`[data-cy='${fieldCy}'] .mdx-visual-editor__content`)
    .click()
    .type(text);
}

describe("instagreg", () => {
  beforeEach(() => {
    cy.viewport("iphone-6");
  });

  // Generated by Cypress Author on 2026-10-14
  it("creates a post with the reusable editor → the new text appears in the list", () => {
    cy.uniqueRecordName("post").then((postText) => {
      cy.signInAsUser(0);

      cy.intercept("POST", "/api/views/igPosts/new/item").as("createPost");
      cy.intercept("GET", "/api/views/igPosts/list/get").as("listGet");

      cy.visit("/instagreg");
      cy.waitForClerkLoaded();
      cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should("exist");
      cy.wait("@listGet");

      cy.intercept("GET", "/api/views/igPosts/list/get").as("listRefetch");

      typeInEditor("p_text_content_field", postText);
      // Submit via the button (Enter inserts a newline in the editor).
      cy.get("[data-cy='create_ig_post_submit']").click();

      cy.wait("@createPost").its("response.statusCode").should("eq", 202);
      cy.wait("@listRefetch");

      cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should(
        "contain",
        postText,
      );
    });
  });

  // Generated by Cypress Author on 2026-10-14
  it("plain Enter in the editor inserts a newline and issues no request", () => {
    cy.signInAsUser(0);
    cy.intercept("POST", "/api/views/igPosts/new/item").as("createPost");
    cy.intercept("GET", "/api/views/igPosts/list/get").as("listGet");

    cy.visit("/instagreg");
    cy.waitForClerkLoaded();
    cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should("exist");
    cy.wait("@listGet");

    cy.get(
      "[data-cy='p_text_content_field'] [data-cy='mdx-visual-editor']",
      { timeout: 20000 },
    ).should("exist");
    cy.get("[data-cy='p_text_content_field'] .mdx-visual-editor__content")
      .click()
      .type("line one{enter}line two");

    // A newline keeps both lines in the editor and starts no create request.
    cy.get("[data-cy='p_text_content_field'] .mdx-visual-editor__content")
      .should("contain.text", "line one")
      .and("contain.text", "line two");
    cy.get("@createPost.all").should("have.length", 0);
  });

  // Generated by Cypress Author on 2026-10-14
  it("Ctrl+Enter in the editor submits the post", () => {
    cy.uniqueRecordName("post").then((postText) => {
      cy.signInAsUser(0);
      cy.intercept("POST", "/api/views/igPosts/new/item").as("createPost");
      cy.intercept("GET", "/api/views/igPosts/list/get").as("listGet");

      cy.visit("/instagreg");
      cy.waitForClerkLoaded();
      cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should("exist");
      cy.wait("@listGet");

      cy.get("[data-cy='p_text_content_field'] .mdx-visual-editor__content")
        .click()
        .type(`${postText}{ctrl+enter}`);

      cy.wait("@createPost").its("response.statusCode").should("eq", 202);
    });
  });

  // Generated by Cypress Author on 2026-10-14
  it("edits a seeded post → the list shows the updated heading", () => {
    cy.uniqueRecordName("post").then((postText) => {
      ownerId().then((identifier) => {
        cy.task("createIgPostAsUser", {
          identifier,
          p_text_content: postText,
          p_public: true,
        });
      });

      cy.signInAsUser(0);
      cy.intercept("PATCH", "/api/views/igPosts/one/patch").as("updatePost");
      cy.visit("/instagreg");

      cy.contains("[data-cy='igPosts_list'] article", postText, {
        timeout: 20000,
      })
        .find("[data-cy='ig_post_actions']")
        .click();

      cy.get("[data-cy='ig_post_edit']").click();

      // The edit editor hydrates with the fetched content, then we replace it.
      cy.get(
        "[data-cy='edit_p_text_content_field'] [data-cy='mdx-visual-editor']",
        { timeout: 20000 },
      ).should("exist");
      cy.get("[data-cy='edit_p_text_content_field'] .mdx-visual-editor__content")
        .should("contain.text", postText)
        .type("{selectall}{del}")
        .type(`## ${postText}`);

      cy.get("[data-cy='edit_ig_post_submit']").click();

      cy.wait("@updatePost").its("response.statusCode").should("eq", 202);

      cy.get("[data-cy='ig_post_body'] h2", { timeout: 20000 }).should(
        "contain",
        postText,
      );
    });
  });

  // Generated by Cypress Author on 2026-10-14
  it("supports Vim mode in the create editor", () => {
    cy.signInAsUser(0);
    cy.visit("/instagreg");
    cy.waitForClerkLoaded();
    cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should("exist");

    // Toggle Vim mode; the CodeMirror surface replaces the visual editor while
    // the draft is preserved.
    cy.get("[data-cy='p_text_content_field'] [data-cy='mdx-visual-editor']", {
      timeout: 20000,
    }).should("exist");
    cy.get("[data-cy='p_text_content_field'] [data-cy='mdx-vim-toggle']").click();
    cy.get("[data-cy='p_text_content_field'] [data-cy='mdx-vim-editor']", {
      timeout: 20000,
    }).should("exist");
  });

  // Generated by Cypress Author on 2026-10-14
  it("another user opens the feed → a seeded public post is visible", () => {
    cy.uniqueRecordName("post").then((postText) => {
      ownerId().then((identifier) => {
        cy.task("createIgPostAsUser", {
          identifier,
          p_text_content: postText,
          p_public: true,
        });
      });

      cy.signInAsUser(1);
      cy.visit("/instagreg");

      cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should(
        "contain",
        postText,
      );
    });
  });

  // Generated by Cypress Author on 2026-10-14
  it("another user is viewing the feed → a newly seeded public post appears", () => {
    cy.uniqueRecordName("live").then((liveText) => {
      cy.signInAsUser(1);

      cy.intercept("GET", "/api/views/igPosts/list/get").as("listGet");

      cy.visit("/instagreg");
      cy.waitForClerkLoaded();
      cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should("exist");
      cy.wait("@listGet").its("response.statusCode").should("eq", 202);
      cy.get("[data-cy='mqtt_connected']", { timeout: 20000 }).should("exist");

      ownerId().then((identifier) => {
        cy.task("createIgPostAsUser", {
          identifier,
          p_text_content: liveText,
          p_public: true,
        })
          .its("post_id")
          .should("be.a", "string");
      });

      cy.get("[data-cy='igPosts_list']", { timeout: 20000 }).should(
        "contain",
        liveText,
      );
      cy.location("pathname").should("include", "instagreg");
    });
  });
});
